const assert = require('node:assert/strict');
const path = require('node:path');
exports.run = async function(browser,url,report) {
  const results=[];
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const login=async role=> { await page.locator(`[data-mvp-role="${role}"]`).click(); await page.locator('#enter').click(); };
  const nav=async name=>page.locator(`#mobile-nav [data-page="${name}"]`).click();
  const screenshot=async name=> { await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:path.join(report,name+'.png'),animations:'disabled'}); };
  try {
    await page.goto(url); await login('Familia');
    await nav('more'); await page.locator('#content [data-page="settings"]').click();
    await page.locator('[data-pref="theme"][data-value="dark"]').click();
    await page.reload(); assert.ok(await page.locator('#welcome').isVisible());
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
    await login('Cuidador'); assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
    await screenshot('cuidador-oscuro');
    await page.locator('#logout').click(); await login('Familia');
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
    await screenshot('familia-oscuro');
    results.push('Acceso tras recarga y tema estable al cambiar entre cuentas');
    await nav('marketplace');
    assert.equal(await page.locator('.caregiver-card').count(),7);
    await page.locator('[data-action="contact-caregiver"][data-id="cg4"]').click();
    await page.locator('#caregiver-message').fill('Consulta privada para Marta');
    await page.locator('#caregiver-contact-form [type="submit"]').click();
    await page.locator('#logout').click(); await login('Cuidador'); await nav('inquiries');
    assert.equal(await page.locator('[data-action="open-inquiry"]').count(),0);
    assert.ok(!(await page.locator('#content').textContent()).includes('Consulta privada para Marta'));
    await page.locator('#logout').click(); await login('Familia'); await nav('marketplace');
    await page.locator('[data-action="contact-caregiver"][data-id="cg1"]').click();
    await page.locator('#caregiver-message').fill('Consulta para Rosa'); await page.locator('#caregiver-contact-form [type="submit"]').click();
    await page.locator('#logout').click(); await login('Cuidador'); await nav('inquiries');
    await page.locator('[data-action="open-inquiry"][data-id="cg1"]').click();
    assert.ok((await page.locator('#content').textContent()).includes('Consulta para Rosa'));
    await page.locator('.caregiver-reply-form textarea').fill('Sí, María. Podemos coordinarlo.');
    await page.locator('.caregiver-reply-form [type="submit"]').click();
    results.push('Marketplace: siete cuidadoras; Rosa solo ve y responde consultas propias');
    await nav('routine'); await page.locator('#content [data-page="calendar"]').click();
    await page.locator('[data-action="edit-appointment"]').first().click();
    await page.locator('#appointment-date').fill('2026-10-12'); await page.locator('#appointment-time').fill('11:30');
    await page.locator('#appointment-form [type="submit"]').click();
    assert.ok((await page.locator('.selected-appointments').textContent()).includes('11:30'));
    await page.locator('#logout').click(); await login('Familia'); await nav('health');
    assert.equal(await page.locator('.wearable-grid article').count(),6);
    await screenshot('familia-salud');
    await page.locator('#notifications-button').click();
    await page.locator('.notification-item').filter({hasText:'Control actualizado'}).first().click();
    assert.equal(await page.locator('html').getAttribute('data-page'),'calendar');
    assert.ok((await page.locator('.selected-appointments').textContent()).includes('12 de octubre'));
    await page.locator('[data-action="go-back"]').click();
    assert.equal(await page.locator('html').getAttribute('data-page'),'health');
    await nav('chat'); await page.locator('#chat-message').fill('Mensaje para probar el aviso');
    await page.locator('#chat-form [type="submit"]').click();
    await page.locator('#logout').click(); await login('Cuidador'); await page.locator('#notifications-button').click();
    await page.locator('.notification-item').filter({hasText:'Nuevo mensaje del círculo'}).first().click();
    assert.equal(await page.locator('html').getAttribute('data-page'),'chat');
    results.push('Cuidador modifica fecha y hora; Familia recibe control y avisos abren su sección; Volver retorna');
    await page.locator('#logout').click(); await page.setViewportSize({width:1024,height:768}); await login('Adulto mayor');
    await page.locator('#content [data-page="photos"]').click();
    await page.locator('[data-action="photo-fullscreen"]').first().click();
    assert.ok(await page.locator('#photo-viewer').isVisible());
    await page.screenshot({path:path.join(report,'adulto-foto-completa.png')});
    await page.locator('[data-action="viewer-close"]').click();
    assert.ok(!(await page.locator('#photo-viewer').isVisible()));
    await page.locator('[data-action="go-back"]').click();
    await page.locator('#content [data-page="entertainment"]').click();
    await page.locator('[data-action="game-dot"][data-index="3"]').click();
    assert.ok((await page.locator('.game-feedback').first().textContent()).includes('busca el 1'));
    for(let i=1;i<=5;i++) await page.locator(`[data-action="game-dot"][data-index="${i}"]`).click();
    assert.ok((await page.locator('.game-feedback').first().textContent()).includes('Completaste'));
    await page.locator('.recreation-grid').screenshot({path:path.join(report,'adulto-juego-puntos.png'),animations:'disabled'});
    await page.locator('[data-action="game-select"][data-id="puzzle"]').click();
    const from=page.locator('.puzzle-piece[data-index="0"]'), to=page.locator('.puzzle-piece[data-index="1"]');
    await from.scrollIntoViewIfNeeded();
    const a=await from.boundingBox(), b=await to.boundingBox();
    await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
    await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:10}); await page.mouse.up();
    assert.ok((await page.locator('.puzzle-piece[data-index="0"]').getAttribute('aria-label')).startsWith('Pieza 1,'));
    for(const i of [1,3,2,3]) await page.locator(`.puzzle-piece[data-index="${i}"]`).tap();
    assert.equal(await page.locator('.puzzle-piece:disabled').count(),4);
    await page.locator('.recreation-grid').screenshot({path:path.join(report,'adulto-juego-rompecabezas.png'),animations:'disabled'});
    await page.locator('[data-action="game-select"][data-id="differences"]').click();
    await page.locator('[data-action="game-difference-hint"]').tap();
    for(const id of ['sun','flower','butterfly']) await page.locator(`[data-action="game-difference"][data-id="${id}"]`).tap();
    assert.equal(await page.locator('.difference-hit.found').count(),3);
    await page.locator('.recreation-grid').screenshot({path:path.join(report,'adulto-juego-diferencias.png'),animations:'disabled'});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(errors,[]);
    results.push('Adulto mayor: visor completo y salida; tres juegos completados, rompecabezas por arrastre y toque');
    return results;
  } finally { await page.close(); }
};
